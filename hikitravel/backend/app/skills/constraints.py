"""用户的饮食禁忌（只保留能可靠判定的那一部分）。

这个模块的原则是：**宁可少判，也不乱判**。

历史背景：这里原来还管「排斥项」（爬山 / 排队 / 网红打卡）。但实测证明我们
**没有"这个景点要不要爬山"的可信数据**——高德的 type 字段偶尔给到"山岳"，
多数只到"风景名胜;风景名胜;风景名胜"这一层。按名字匹配的结果是：

    浙江省博物馆(孤山馆区) → 判成「爬山」   （博物馆）
    巍山古城              → 判成「爬山」   （平的古城）
    洱源天和山庄           → 判成「爬山」   （度假山庄）
    雷峰塔景区             → 判成「爬山」   （命中的是「峰」）

16 个命中里至少 5 个是明显误判。**用一个不可靠的判据去自动改用户的行程，
比不做更糟**，所以排斥项整个删掉了：画像字段、意图抽取、体检提示词、前端表单
里的那一组选项，全部一起拿掉（现在 `UserPreference` 里已经没有这个字段）。

「饮食禁忌」能保留，是因为它的判据可靠：店名里有「海鲜」就是海鲜店。
实测在 91 家真实餐厅上，「无海鲜」排掉的 25 家全是真海鲜店
（海鲜面 / 海鲜蒸菜 / 海鲜火锅），零误判。

同时去掉了两处不必要的复杂度：

- 「符合偏好加分」（清真 / 素食加分）：收益很小，却多引入一处可能出错的判断；
- 「不吃辣」的硬排除：火锅有清汤锅，而数据只有店名，排除掉是错的。
"""
from typing import Dict, Iterable, Optional, Tuple

#: 禁忌 -> 店名里出现就直接排除的词。
#: 只放"命中就一定对"的词：命中就排除，判不出来的保留（宁少不滥）。
DIET_EXCLUDE: Dict[str, Tuple[str, ...]] = {
    "无海鲜": ("海鲜", "海产", "鱼", "蟹", "虾", "蚝", "蚌", "贝", "鱿", "章鱼"),
    "海鲜过敏": ("海鲜", "海产", "鱼", "蟹", "虾", "蚝", "蚌", "贝", "鱿", "章鱼"),
    "清真": (
        "猪", "排骨", "五花", "腊肉", "香肠", "培根", "火腿", "卤肉", "大肠",
        "红烧肉", "扣肉", "回锅肉", "猪脚", "猪蹄",
    ),
}

#: 禁忌 -> 追加到餐厅检索的关键词。
#: 只能加"正向"词（去找清真餐厅、素食店）；把禁忌本身当关键词去搜是反向的，
#: 那是这里曾经的一个 bug。
DIET_SEARCH_KEYWORDS: Dict[str, str] = {
    "清真": "清真餐厅",
    "素食": "素食",
}


def restaurant_excluded(name: str, restrictions: Iterable[str]) -> Optional[str]:
    """这家餐厅是否触犯饮食禁忌；触犯时返回原因（用于体检里说明）。"""
    for item in restrictions:
        for word in DIET_EXCLUDE.get(item, ()):
            if word in (name or ""):
                return f"{item}（店名含「{word}」）"
    return None
